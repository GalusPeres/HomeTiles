#!/usr/bin/env node
// Generates the Cyrillic fallback fonts of the panel text fonts:
//   src/fonts/ui_font_cyrillic_<size>.c
// and hangs each one on its Latin font (ui_font_<size>.c `.fallback`), so a
// Russian text or a Cyrillic Home Assistant name draws in every text size.
// The Latin fonts carry Latin-1, Latin Extended-A and punctuation
// uncompressed; the Cyrillic block (U+0400-U+045F, Ukrainian Ґ ґ) is
// compressed and unpacked once per glyph (src/fonts/glyph_cache.c). The clock
// digit fonts (80, 96) carry no letters and get none.
//
// Same converter and font as the Latin fonts: lv_font_conv 1.5.3 and Inter
// 4.1 Regular as TTF (the release zip's extras/ttf/Inter-Regular.ttf, or the
// repository's docs/font-files/Inter-Regular.woff2 at tag v4.1 saved as TTF;
// both give the same glyphs as src/fonts/ui_font_20.c).
//
//   node tools/generate-cyrillic-fonts.mjs --font <Inter-Regular.ttf> [--converter <lv_font_conv.js>]
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync, execSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONVERTER = 'lv_font_conv@1.5.3';
export const RANGE = '0x0400-0x045F,0x0490-0x0491';
// Every text size of ui_font_for_size (src/fonts/ui_fonts.h).
export const SIZES = [12, 14, 16, 20, 24, 28, 32, 40, 48, 56, 64, 72];

function argument(name) {
  const index = process.argv.indexOf(name);
  return index > 0 ? process.argv[index + 1] : undefined;
}

function postProcess(source, size) {
  const name = `ui_font_cyrillic_${size}`;
  const replace = (pattern, replacement) => {
    if (!pattern.test(source)) throw new Error(`${name}: pattern not found: ${pattern}`);
    source = source.replace(pattern, replacement);
  };
  replace(/^ \* Opts: .+$/m,
    ` * Opts: --bpp 4 --format lvgl --lv-include lvgl.h --size ${size} --font Inter-Regular.ttf ` +
    `--range ${RANGE} --lv-font-name ${name} --output ${name}.c\n` +
    ' * Generated by tools/generate-cyrillic-fonts.mjs. Do not edit by hand.');
  replace(/^(#endif)\r?\n\r?\n(#ifndef UI_FONT_CYRILLIC_)/m, '$1\n\n#include "src/fonts/glyph_cache.h"\n\n$2');
  replace(/\.get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,.*$/m,
    '.get_glyph_bitmap = glyph_cache_bitmap,    /*Unpacked once, src/fonts/glyph_cache.c*/');
  return source.replace(/\r\n/g, '\n').trimEnd() + '\n';
}

// The Latin font's fallback, keeping the file's own line ends.
function hangFallback(size) {
  const file = path.join(root, 'src/fonts', `ui_font_${size}.c`);
  const original = fs.readFileSync(file, 'utf8');
  const crlf = original.includes('\r\n');
  let source = original.replace(/\r\n/g, '\n');
  const name = `ui_font_cyrillic_${size}`;
  if (!source.includes(`extern const lv_font_t ${name};`)) {
    const include = /^#include "src\/fonts\/glyph_cache\.h"$/m;
    if (!include.test(source)) throw new Error(`${file}: no glyph_cache include`);
    source = source.replace(include, `extern const lv_font_t ${name};\n\n#include "src/fonts/glyph_cache.h"`);
  }
  if (!source.includes(`.fallback = &${name},`)) {
    if (!/\.fallback = NULL,/.test(source)) throw new Error(`${file}: no empty fallback`);
    source = source.replace(/\.fallback = NULL,/, `.fallback = &${name},`);
  }
  fs.writeFileSync(file, crlf ? source.replace(/\n/g, '\r\n') : source);
}

function converterPath(temp) {
  const given = argument('--converter');
  if (given) return path.resolve(given);
  execSync(`npm pack ${CONVERTER} --pack-destination "${temp}"`, {stdio: 'ignore'});
  const archive = fs.readdirSync(temp).find((f) => f.endsWith('.tgz'));
  if (!archive) throw new Error(`Unable to download ${CONVERTER}`);
  execFileSync('tar', ['-xf', archive, '-C', '.'], {cwd: temp});
  return path.join(temp, 'package', 'lv_font_conv.js');
}

function writeFonts() {
  const font = argument('--font');
  if (!font || !fs.existsSync(font)) throw new Error('Pass --font <Inter 4.1 Inter-Regular.ttf>');
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'HomeTiles-cyrillic-'));
  try {
    const converter = converterPath(temp);
    for (const size of SIZES) {
      const name = `ui_font_cyrillic_${size}`;
      const generated = path.join(temp, `${name}.c`);
      execFileSync(process.execPath, [converter, '--bpp', '4', '--format', 'lvgl', '--lv-include', 'lvgl.h',
        '--size', String(size), '--font', path.resolve(font), '--range', RANGE, '--lv-font-name', name,
        '-o', generated], {stdio: 'inherit'});
      const output = path.join(root, 'src/fonts', `${name}.c`);
      fs.writeFileSync(output, postProcess(fs.readFileSync(generated, 'utf8'), size));
      hangFallback(size);
      console.log(`Generated ${path.relative(root, output)}`);
    }
  } finally {
    fs.rmSync(temp, {recursive: true, force: true});
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) writeFonts();
