#!/usr/bin/env node
// Embeds one microWakeWord model (esphome/micro-wake-word-models, Apache-2.0)
// in the firmware: writes src/audio/wakeword/models/<name>_model.{h,cpp} from
// the model's .tflite file and its JSON manifest.
//
// Usage:
//   node tools/generate-wake-word-model.mjs <model.tflite> <model.json> <name>
//
// The .cpp holds the flatbuffer as a 16-byte aligned const array (flash);
// the header records the manifest's detection parameters and the SHA256 of
// the embedded bytes, which src/audio/wakeword/models/PROVENANCE.md repeats.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [tflitePath, jsonPath, name] = process.argv.slice(2);
if (!tflitePath || !jsonPath || !/^[a-z0-9_]{1,32}$/.test(name || '')) {
  console.error('Usage: generate-wake-word-model.mjs <model.tflite> <model.json> <name>');
  process.exit(2);
}

const model = fs.readFileSync(tflitePath);
const manifest = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
const micro = manifest.micro || {};
for (const key of ['probability_cutoff', 'sliding_window_size', 'tensor_arena_size',
                   'feature_step_size']) {
  if (typeof micro[key] !== 'number') throw new Error(`manifest lacks micro.${key}`);
}
if (manifest.type !== 'micro') throw new Error('not a microWakeWord manifest');
// "TFL3" flatbuffer identifier at offset 4.
if (model.subarray(4, 8).toString('latin1') !== 'TFL3') throw new Error('not a TFLite model');

const sha256 = crypto.createHash('sha256').update(model).digest('hex');
const symbol = name.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const outDir = path.join(root, 'src/audio/wakeword/models');
fs.mkdirSync(outDir, {recursive: true});

const header = `#pragma once

// Generated by tools/generate-wake-word-model.mjs; do not edit.
// microWakeWord model "${manifest.wake_word}" (${path.basename(tflitePath)}, manifest
// version ${manifest.version}), Apache-2.0, see PROVENANCE.md in this folder.
// SHA256 ${sha256}

#include <stddef.h>
#include <stdint.h>

namespace wake_word_models {

extern const uint8_t k${symbol}Model[];
constexpr size_t k${symbol}ModelSize = ${model.length};
constexpr float k${symbol}ProbabilityCutoff = ${micro.probability_cutoff}f;
constexpr uint8_t k${symbol}SlidingWindowSize = ${micro.sliding_window_size};
constexpr size_t k${symbol}TensorArenaSize = ${micro.tensor_arena_size};
constexpr uint8_t k${symbol}FeatureStepMs = ${micro.feature_step_size};

}  // namespace wake_word_models
`;

const lines = [];
for (let i = 0; i < model.length; i += 16) {
  const row = [...model.subarray(i, i + 16)].map((b) => `0x${b.toString(16).padStart(2, '0')}`);
  lines.push(`    ${row.join(', ')},`);
}
const source = `// Generated by tools/generate-wake-word-model.mjs; do not edit.
// SHA256 ${sha256}
#include "src/audio/wakeword/models/${name}_model.h"

#include "src/audio/speaker_select.h"

// Only the wake word profiles carry the model in flash.
#if defined(HOMETILES_WAKE_WORD)
namespace wake_word_models {

// TFLite Micro reads the flatbuffer in place; 16-byte alignment keeps its
// tensor data aligned.
alignas(16) const uint8_t k${symbol}Model[] = {
${lines.join('\n')}
};

}  // namespace wake_word_models
#endif  // defined(HOMETILES_WAKE_WORD)
`;

fs.writeFileSync(path.join(outDir, `${name}_model.h`), header);
fs.writeFileSync(path.join(outDir, `${name}_model.cpp`), source);
console.log(`${name}: ${model.length} bytes, SHA256 ${sha256}`);
