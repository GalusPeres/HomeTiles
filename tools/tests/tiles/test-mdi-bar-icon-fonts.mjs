// The tile bars (Lock thumb, Alarm modes, Fan thumb) draw their icons from
// small generated MDI fonts instead of scaling FONT_MDI_ICONS with an LVGL
// transform (a layer per label on every frame). Each font must hold exactly
// the bar icons, keep its generator header, and stay in the host LVGL build.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {BAR_ICONS, SIZES, barIconCodepoints, rangeText} from '../../generate-mdi-bar-icon-fonts.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n?/g, '\n');

assert.deepEqual(SIZES, [15, 18, 22, 26, 34]);
for (const name of ['lock', 'lock-open-variant', 'lock-clock', 'home', 'moon-waning-crescent', 'airplane',
  'shield', 'shield-off', 'fan', 'fan-off']) {
  assert.ok(BAR_ICONS.includes(name), `bar icon ${name}`);
}
const codepoints = barIconCodepoints();
assert.equal(codepoints.length, BAR_ICONS.length);
const range = rangeText(codepoints);

for (const size of SIZES) {
  const name = `mdi_bar_icons_${size}`;
  const font = read(`src/fonts/${name}.c`);
  assert.match(font, /Generated by tools\/generate-mdi-bar-icon-fonts\.mjs\. Do not edit by hand\./, name);
  assert.ok(font.includes(`--size ${size} --font materialdesignicons-webfont.woff --range ${range} `), `${name} range`);
  assert.ok(font.includes('#include "lvgl.h"') && !font.includes('lvgl/lvgl.h'), `${name} include`);
  const glyphs = [...font.matchAll(/\/\* U\+([0-9A-F]+) /g)].map((m) => parseInt(m[1], 16));
  assert.deepEqual(glyphs, codepoints, `${name} glyphs`);
  assert.match(font, new RegExp(`const lv_font_t ${name} = \\{`), `${name} descriptor`);
}

const header = read('src/tiles/icons/mdi_bar_icons.h');
assert.match(header, /extern "C" \{\s*#endif\s*LV_FONT_DECLARE\(mdi_bar_icons_15\);\s*LV_FONT_DECLARE\(mdi_bar_icons_18\);\s*LV_FONT_DECLARE\(mdi_bar_icons_22\);\s*LV_FONT_DECLARE\(mdi_bar_icons_26\);\s*LV_FONT_DECLARE\(mdi_bar_icons_34\);/);
assert.match(header, /inline const lv_font_t\* for_bar\(int base\)/);
assert.match(header, /const int want = base \* 45 \/ 100;/);
assert.match(read('tools/lib/lvgl-host.mjs'), /mdi_bar_icons_\(15\|18\|22\|26\|34\)/);
console.log('Bar icon fonts: exactly the bar icons at 15/18/22/26/34 px, declared with C linkage');
